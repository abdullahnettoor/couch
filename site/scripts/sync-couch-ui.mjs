#!/usr/bin/env node
/**
 * Copies Couch's real UI into src/couch-ui/ so the landing page's mocks stay faithful to the app.
 *
 *   pnpm sync:couch            (reads the app repo this site lives in, or COUCH_REPO=/path/to/couch)
 *   pnpm sync:couch --check    (writes nothing; regenerates every output in memory and exits 1 if any committed
 *                               file differs or is missing; only the recorded Couch commit hash is ignored)
 *
 * The Couch repo is only ever read. Output (committed, so the site builds without the Couch repo):
 *   screen.css   src/renderer/glass.css + home.css, with Couch's glass tokens, every selector scoped under .cu
 *   remote.css   the <style> of the Remote page (src/main/remote/page.ts), scoped under .cr
 *   remote.html  the Remote page's idle view (top strip, buttons, Apps row, D-pad, volume pill), as Couch builds it
 *   data.json    icons, App marks, the Couch wallpaper, motion values (each with its source), source hashes
 * Everything copied is GPL-3.0-or-later, like Couch. See README.
 */
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { namespace, scope } from "./css-scope.mjs";

const site = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const couch = resolve(process.env.COUCH_REPO ?? join(site, ".."));
const out = join(site, "src/couch-ui");

const checkOnly = process.argv.includes("--check");
const outputs = {};
const put = (name, text) => { outputs[name] = text; };
const read = (p) => readFileSync(join(couch, p), "utf8");
const sha = (p) => createHash("sha256").update(read(p)).digest("hex").slice(0, 12);
const mod = (p) => import(pathToFileURL(join(couch, p)).href);

let commit = "unknown";
try {
  commit = execFileSync("git", ["-C", couch, "rev-parse", "--short", "HEAD"]).toString().trim();
} catch {}

const header = (files) =>
  `/* GENERATED by scripts/sync-couch-ui.mjs. Do not edit.\n * Copied from the Couch repo (commit ${commit}): ${files.join(", ")}.\n * GPL-3.0-or-later, like Couch. Selectors are scoped under the root class below. */\n`;

/** The first rule whose selector list is exactly `selector`; returns its declarations. */
const ruleOf = (css, selector) => {
  const flat = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const re = new RegExp(`(?:^|\\})\\s*${selector.replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replace(/\s+/g, "\\s*").replace(/,/g, "\\s*,\\s*")}\\s*\\{([^}]*)\\}`);
  const m = re.exec(flat);
  if (!m) throw new Error(`rule not found: ${selector}`);
  return m[1].replace(/\s+/g, " ").trim();
};
const decl = (body, prop) => {
  const m = new RegExp(`(?:^|;|\\s)${prop}:\\s*([^;]+)`).exec(body);
  if (!m) throw new Error(`declaration not found: ${prop}`);
  return m[1].trim();
};

// ---- Screen CSS ----
const look = await mod("src/shared/look.ts");
const glass = read("src/renderer/glass.css");
const home = read("src/renderer/home.css");
const screenCss =
  header(["src/renderer/glass.css", "src/renderer/home.css", "src/shared/look.ts"]) +
  look.lookCss(look.GLASS, { selector: ".cu", unit: "var(--u)" }) +
  "\n" +
  namespace(scope(glass, ".cu") + scope(home, ".cu"), "cu-");
put("screen.css", screenCss);

// ---- Remote page ----
const { REMOTE_PAGE } = await mod("src/main/remote/page.ts");
const pageCss = /<style>([\s\S]*?)<\/style>/.exec(REMOTE_PAGE)[1];
const remoteCss =
  header(["src/main/remote/page.ts (its <style>)", "src/shared/look.ts"]) +
  namespace(scope(pageCss, ".cr", { active: true }), "cr-");
put("remote.css", remoteCss);

const { ICON_MARKUP } = await mod("src/shared/icons.ts");
const { APP_ENTRIES } = await mod("src/main/apps/index.ts");
const { WALLPAPERS, wallpaperVars } = await mod("src/shared/wallpapers.ts");

// Each App mark is one <symbol> in a sprite (the YouTube mark carries an inline PNG: write it once).
const sprite = {};
const useOf = (id, svg) => {
  const vb = /viewBox="([^"]+)"/.exec(svg)[1];
  sprite[id] = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
  return { viewBox: vb, symbol: `cu-${id}` };
};
const apps = APP_ENTRIES.map((a) => {
  if (/<defs|<image/.test(a.icon)) return { id: a.id, label: a.label, ...useOf(a.id, a.icon) };
  return { id: a.id, label: a.label, svg: a.icon };
});

const idle = (() => {
  const main = /<main id="controls">[\s\S]*?<\/main>/.exec(REMOTE_PAGE)[0];
  const top = /<div class="top">[\s\S]*?<\/div><\/div>(?=\n<div class="conn")/.exec(REMOTE_PAGE)[0];
  let h = main
    .replace(/<button id="upd"[^>]*hidden>[\s\S]*?<\/button>/, "")
    .replace(/<button class="cw"[\s\S]*?<\/button>/, "")
    .replace(/<div class="note-card"[\s\S]*?<\/ol><\/div>/, "")
    .replace(/<(button|a) class="search"[^>]*hidden>[\s\S]*?<\/\1>/g, "")
    .replace(/<div class="other"[^>]*>[^<]*<\/div>/, "")
    // Home layout, as render() sets it: no Back button, the gear shows
    .replace(/<button data-cmd="back"[^>]*id="id-back"[^>]*><\/button>/, "")
    .replace(/(<button id="gear"[^>]*?) hidden>/, "$1>")
    .replace(/<div class="apps"[^>]*hidden><\/div>/, `<div class="apps few" role="group" aria-label="Apps">__APPS__</div>`);
  h = `${top}\n${h}`;
  h = h
    .replace(/ id="[^"]*"/g, "")
    .replace(/<b role="status" aria-label="Volume"><\/b>/, '<b role="status" aria-label="Volume">35</b>')
    .replace(/(<b>)(<\/b>)/, "$1Home$2")
    .replace(/(<span id="status">|<span>)Connecting…/, "$1Connected")
    .replace(/(Connected<\/span>)<span><\/span>/, "$1<span> · 1 phone</span>");
  // fill [data-i] buttons with their Phosphor icon, as the page's own script does
  h = h.replace(/(<(?:button|span)[^>]*\sdata-i="(\w+)"[^>]*>)/g, (_m, tag, name) => {
    if (!ICON_MARKUP[name]) throw new Error(`no icon ${name}`);
    return `${tag}<svg class="i" viewBox="0 0 256 256" aria-hidden="true">${ICON_MARKUP[name]}</svg>`;
  });
  return h;
})();
if (/Connecting| hidden/.test(idle)) throw new Error("idle Remote markup still has hidden or unfilled parts");
put("remote.html", `<!-- GENERATED by scripts/sync-couch-ui.mjs from src/main/remote/page.ts (Couch ${commit}), GPL-3.0-or-later -->\n${idle}\n`);

// ---- Motion: the values Couch really uses, each with its source ----
const motion = {
  ease: { value: look.GLASS.motion.ease.glass, source: "src/shared/look.ts GLASS.motion.ease.glass (--ease-glass)" },
  tileFocus: {
    transition: decl(ruleOf(glass, ".g-tile"), "transition"),
    focused: decl(ruleOf(glass, ".focused > .g-tile,.g-tile.focused"), "transform"),
    source: "src/renderer/glass.css .g-tile, .focused > .g-tile",
  },
  caption: { transition: decl(ruleOf(glass, ".g-cap"), "transition"), source: "src/renderer/glass.css .g-cap" },
  pill: { transition: decl(ruleOf(glass, ".g-row,.g-pill"), "transition"), focused: decl(ruleOf(glass, ".g-pill.focused"), "transform"), source: "src/renderer/glass.css .g-pill" },
  heroFade: { transition: decl(ruleOf(home, ".h-hero"), "transition"), source: "src/renderer/home.css .h-hero" },
  shelfTrack: { value: /track\.style\.transition = "([^"]+)"/.exec(read("src/renderer/views/library.ts"))[1], source: "src/renderer/views/library.ts (shelf track, chips)" },
  pageScroll: { value: /body\.style\.scrollBehavior = "(\w+)"/.exec(read("src/renderer/views/library.ts"))[1], source: "src/renderer/views/library.ts (Library body scroll)" },
  remotePress: {
    key: decl(ruleOf(pageCss, ".k"), "transition") + "; :active transform " + decl(ruleOf(pageCss, ".k:active"), "transform"),
    bar: decl(ruleOf(pageCss, ".bar button"), "transition") + "; :active transform " + decl(ruleOf(pageCss, ".bar button:active"), "transform"),
    dir: ".dir:active { " + ruleOf(pageCss, ".dir:active") + " }",
    ok: ".ok:active { " + ruleOf(pageCss, ".ok:active") + " }",
    source: "src/main/remote/page.ts <style> (.k, .bar button, .dir, .ok)",
  },
};

// The CSS and the Look's names both say var(--duration-base): write the value the Look gives it.
const lookValue = new Map(look.lookTokens(look.GLASS, "var(--u)"));
const resolveVars = (v) =>
  typeof v === "string" ? v.replace(/var\(--([\w-]+)\)/g, (m, n) => lookValue.get(n) ?? m) : v && typeof v === "object" ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, resolveVars(x)])) : v;
for (const k of Object.keys(motion)) motion[k] = resolveVars(motion[k]);

const wp = WALLPAPERS.find((w) => w.id === "couch");
const data = {
  source: {
    repo: "couch",
    commit,
    files: Object.fromEntries(
      [
        "src/renderer/glass.css",
        "src/renderer/home.css",
        "src/renderer/views/home.ts",
        "src/renderer/views/glass.ts",
        "src/renderer/views/library.ts",
        "src/main/remote/page.ts",
        "src/shared/look.ts",
        "src/shared/icons.ts",
        "src/main/apps/index.ts",
        "src/shared/wallpapers.ts",
        "src/shared/track-code.ts",
        "src/main/apps/youtube/icon.ts",
        "src/main/apps/netflix/icon.ts",
      ].map((f) => [f, sha(f)]),
    ),
  },
  icons: Object.fromEntries(["folder", "gear", "play", "restart"].map((n) => [n, ICON_MARKUP[n]])),
  apps,
  sprite,
  wallpaper: { id: wp.id, vars: wallpaperVars(wp.id) },
  motion,
};
put("data.json", JSON.stringify(data, null, 2) + "\n");

if (checkOnly) {
  // Regenerated in memory vs committed. The recorded commit hash is ignored: only content differences count.
  let recorded = null;
  try { recorded = JSON.parse(readFileSync(join(out, "data.json"), "utf8")).source.commit; } catch {}
  const norm = (t, c) => (c ? t.split(c).join("<commit>") : t);
  const bad = Object.entries(outputs).filter(([name, text]) => {
    const f = join(out, name);
    return !existsSync(f) || norm(readFileSync(f, "utf8"), recorded) !== norm(text, commit);
  }).map(([name]) => name);
  console.log(bad.length ? `out of date or missing: ${bad.join(", ")} (run pnpm sync:couch)` : "src/couch-ui is up to date with Couch");
  process.exit(bad.length ? 1 : 0);
}
mkdirSync(out, { recursive: true });
for (const [name, text] of Object.entries(outputs)) writeFileSync(join(out, name), text);
console.log(`couch-ui synced from ${couch} @ ${commit}`);
